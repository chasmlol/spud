#!/usr/bin/env python3
"""Generates the V0 flyover bench scenarios. Positions are exterior cell grid coordinates
(found with `skytool esm dump Skyrim.esm --type CELL`); re-run after editing.

The quick suite must take 60 s of real time in total, startup included (about 3 s per scenario), so the
recorded parts add up to about 42 s. Each scenario is short and dense: it targets one kind of load rather
than touring the map. A new scenario takes its time from the others."""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent / "scenarios"


def c(x, y):  # cell centre in Skyrim units
    return (x * 4096 + 2048, y * 4096 + 2048)


P = {  # from Skyrim.esm exterior cell EditorIDs (XCLC grid)
    "falkreath": c(-8, -22), "helgen": c(3, -19), "riverwood": c(5, -11), "whiterun": c(5, -2),
    "dawnstar": c(7, 25), "winterhold": c(27, 25), "windhelm": c(32, 8), "solitude": c(-17, 25),
    "markarth": c(-42, 1), "throat": c(13, -13), "ivarstead": c(18, -16), "morthal": c(-10, 15),
    "rorikstead": c(-21, 2),
}


def yaw(a, b):  # Skyrim heading: 0 = north (+Y), 90 = east (+X)
    return math.degrees(math.atan2(b[0] - a[0], b[1] - a[1])) % 360


HEADER = """# Generated by tools/perf/gen_scenarios.py from Skyrim exterior cell positions; coordinates in Skyrim units,
# angles in degrees like the in-game getangle (yaw 0 = north, 90 = east; positive pitch looks down).
# z "+N" = N units above the terrain at that point.
"""


def common(name, desc):
    return HEADER + f"# {desc}\nname {name}\nworld tamriel\nresolution 2560 1440\ndraw_distance 12\n"


def write(name, text):
    (OUT / f"{name}.bench").write_text(text, newline="\n")  # LF like the rest of the repo


# 1. Fast flight: continuous streaming in and out.
route = ["riverwood", "whiterun"]
t = common("tamriel-crossing", "Fast flight Riverwood -> Whiterun (~550 m at 80 m/s, ~7 s).")
a, b = P[route[0]], P[route[1]]
t += f"start {a[0]} {a[1]} +3000 {yaw(a, b):.1f} 10\nsegment crossing\n"
for i in range(1, len(route)):
    prev, cur = P[route[i - 1]], P[route[i]]
    nxt = P[route[i + 1]] if i + 1 < len(route) else None
    heading = yaw(cur, nxt) if nxt else yaw(prev, cur)
    t += f"fly {cur[0]} {cur[1]} +3000 {heading:.1f} 10 80\n"
write("tamriel-crossing", t)

# 2. Instant jumps between distant regions: worst-case streaming; no frame may spike.
jumps = ["solitude", "windhelm", "markarth", "falkreath", "whiterun"]
t = common("teleport-storm", "Five instant jumps between distant regions, 1.4 s each (~7 s).")
w = P["whiterun"]
t += f"start {w[0]} {w[1]} +2500 0 10\nsegment storm\n"
for j in jumps:
    p = P[j]
    t += f"teleport {p[0]} {p[1]} +2500 45 10\nhold 1.4\n"
write("teleport-storm", t)

# 3. Orbit of a dense area (Whiterun walls and plains), looking at the centre.
t = common("city-orbit", "Orbit Whiterun at ~85 m radius, 40 m up, looking at the city (~7 s).")
cx, cy = P["whiterun"][0] - 2048, P["whiterun"][1] - 2048  # corner shared by the city cells
r = 6000
pts = []
for k in range(0, 25):
    ang = 2 * math.pi * k / 24
    x, y = cx + r * math.sin(ang), cy + r * math.cos(ang)
    pts.append((x, y, yaw((x, y), (cx, cy))))
t += f"start {pts[0][0]:.0f} {pts[0][1]:.0f} +2800 {pts[0][2]:.1f} 15\nsegment orbit\n"
for x, y, h in pts[1:]:
    t += f"fly {x:.0f} {y:.0f} +2800 {h:.1f} 15 75\n"
write("city-orbit", t)

# 4. Low flight through dense pine forest: overdraw, alpha test, foliage.
t = common("forest-low", "Low flight (8 m up) through the Falkreath pine forests towards Helgen, 120 m at 25 m/s (~5 s).")
a, b = P["falkreath"], P["helgen"]
h = yaw(a, b)
t += f"start {a[0]} {a[1]} +600 {h:.1f} 5\nsegment forest\n"
for f in (0.09, 0.18):
    x, y = a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f
    t += f"fly {x:.0f} {y:.0f} +600 {h:.1f} 5 25\n"
write("forest-low", t)

# 5. Spins on the highest summit: everything in view at once, frustum churn.
s = P["throat"]
t = common("vista-spin", "Spins above the Throat of the World: 720 degrees level, then 360 looking down (~6 s).")
t += f"start {s[0]} {s[1]} +2000 0 0\nsegment level\nspin 720 3.5\nsegment down\n"
t += f"teleport {s[0]} {s[1]} +2000 0 25\nspin 360 2.5\n"
write("vista-spin", t)

# 6. Through a load door and back: the view through a doorway from both sides, both crossings (the fly path is
# carried through the door with the camera). Door 0001A6F4 of the Bannered Mare, Whiterun.
door_x, door_y, eye = 25726, -7631, -3075
t = common("interior-chain", "Into the Bannered Mare through its door, round the hall and out; then into Blackreach, a world built on the way (~7 s).")
t += f"start {door_x - 420} {door_y} {eye} 90 0\nsegment in\n"
t += f"fly {door_x + 500} {door_y} {eye} 90 0 8\n"
t += f"fly {door_x + 620} {door_y + 90} {eye} 180 0 6\n"
t += f"fly {door_x + 500} {door_y + 180} {eye} 270 0 6\n"
t += f"fly {door_x + 350} {door_y} {eye} 270 0 6\n"
t += f"fly {door_x - 420} {door_y} {eye} 270 0 8\n"
# Then another exterior world, built while the scenario records: from beyond the 40 m at which a door's far space is
# read, straight through door 000EF7AA into Blackreach.
bx, by, bz, nx, ny = 89666, 28051, -5816, 0.766, -0.642
t += "segment far-world\n"
t += f"teleport {bx + nx * 3000:.0f} {by + ny * 3000:.0f} {bz} {yaw((nx, ny), (0, 0)):.1f} 0\n"
t += f"fly {bx - nx * 600:.0f} {by - ny * 600:.0f} {bz} {yaw((nx, ny), (0, 0)):.1f} 0 20\n"
write("interior-chain", t)
print(sorted(p.name for p in OUT.glob("*.bench")))
